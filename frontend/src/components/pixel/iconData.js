export function iconBoxShadow(name, sizePx) {
  const g = GRID[name], c = PAL[name]
  if (!g || !c) return ''
  const sh = []
  g.forEach((row, y) => row.split('').forEach((ch, x) => {
    if (c[ch]) sh.push(`${x * sizePx}px ${y * sizePx}px 0 0 ${c[ch]}`)
  }))
  return sh.join(',')
}
